export function convertPrice(eurPriceStr: string, currency: string): string {
  const match = eurPriceStr.match(/[\d,.]+/);
  if (!match) return eurPriceStr;
  const eurValue = parseFloat(match[0].replace(",", ""));
  if (isNaN(eurValue)) return eurPriceStr;
  if (currency === "EUR") return eurPriceStr;
  const rate = CURRENCY_RATES[currency] || 1;
  const converted = eurValue * rate;
  const symbol = CURRENCY_SYMBOLS[currency] || currency;
  if (["CZK", "HUF"].includes(currency)) {
    return `${symbol} ${Math.round(converted).toLocaleString()}`;
  }
  return `${symbol}${converted.toFixed(2)}`;
}

